"""F030: layer a brand kit over the upstream template without editing it.

    python platform/brand_kit.py list
    python platform/brand_kit.py install shotcraft
    python platform/brand_kit.py verify shotcraft
    python platform/brand_kit.py uninstall shotcraft

The invariant this file exists to enforce
-----------------------------------------
**`upstream/` is read-only** (AGENTS.md hard rule 1). A brand kit is the most
tempting place to break that, because the template's brand strings live in
`template/themes/ui.cjs` as literals and a palette change looks like a
one-character edit.

So this installer does not patch anything. It renders a kit into
`brand-out/<id>/` — generated files beside the repo, outside `upstream/` — as:

  * `tokens.css`      the palette and fonts as CSS custom properties
  * `palette.json`    the same palette in the shape `template/src/themes/palettes.json` expects
  * `brand.json`      the strings, for a renderer to substitute
  * `overlay.css`     the CSS that overrides the template's literal brand values

`verify` proves the invariant rather than asserting it: it hashes every file under
`upstream/` before and after and fails if a single byte moved. A brand kit that
worked by editing the template would fail here, which is the point.

Why not write into the template
-------------------------------
Because `upstream/` is a pinned clone that we delete and re-clone on every bump.
An edit there does not survive `scripts/init.ps1`, and a kit that only works on
one machine's dirty checkout is not a kit, it is a local hack. The overlay is a
separate file the template can be pointed at with `--public-dir` or a
`@import`, which is why `overlay.css` uses `!important` sparingly and targets the
template's actual class names instead of fighting them.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KITS = ROOT / "brand-kits"
OUT = ROOT / "brand-out"
UPSTREAM = ROOT / "upstream" / "video-shotcraft"

# Files the template hardcodes its brand into. Listed so `verify` can report what
# a kit deliberately did NOT change, and so a future maintainer knows these are
# the override targets rather than the override source.
TEMPLATE_BRAND_SURFACE = (
    "template/themes/ui.cjs",
    "template/src/themes/palettes.json",
)


def kit_path(kid: str) -> Path:
    p = KITS / kid / "kit.json"
    if not p.exists():
        raise SystemExit(f"no such kit: {kid} (have: {', '.join(list_kits()) or 'none'})")
    return p


def list_kits() -> list[str]:
    if not KITS.is_dir():
        return []
    return sorted(p.parent.name for p in KITS.glob("*/kit.json"))


def upstream_fingerprint() -> dict[str, str]:
    """sha256 of every tracked file under upstream/. The invariant's evidence."""
    if not UPSTREAM.is_dir():
        return {}
    out = {}
    for f in sorted(UPSTREAM.rglob("*")):
        if not f.is_file() or ".git" in f.parts:
            continue
        try:
            out[f.relative_to(UPSTREAM).as_posix()] = hashlib.sha256(
                f.read_bytes()).hexdigest()
        except OSError:
            continue
    return out


def render(kit: dict) -> dict[str, str]:
    pal = kit["palette"]
    fonts = kit["fonts"]
    type_scale = kit.get("type_scale", {})

    tokens = [
        "/* GENERATED by platform/brand_kit.py from brand-kits/"
        f"{kit['id']}/kit.json v{kit['version']}.",
        "   Do not edit: `python platform/brand_kit.py install "
        f"{kit['id']}` overwrites this file.",
        "   Nothing under upstream/ is touched. */",
        ":root {",
        f"  --font-sans: {fonts['sans']};",
        f"  --font-mono: {fonts['mono']};",
        f"  --font-serif: {fonts['serif']};",
        f"  --font-cjk: {fonts['cjk']};",
    ]
    for k, v in sorted(pal.items()):
        tokens.append(f"  --{k.replace('_', '-')}: {v};")
    for k, v in sorted(type_scale.items()):
        tokens.append(f"  --type-{k}: {v};")
    bs = kit["brand_strings"]
    tokens.append("}")
    tokens.append("")
    tokens.append("/* Brand strings are data, not CSS. A renderer substitutes them;")
    tokens.append("   CSS cannot carry them without hardcoding, which is the thing we")
    tokens.append("   are trying to stop doing. */")
    for k, v in sorted(bs.items()):
        tokens.append(f"/*   --brand-{k.replace('_', '-')}: \"{v}\" */")

    overlay = [
        "/* GENERATED overlay. Import AFTER the template's own stylesheet.",
        "   Targets the template's real class names (see template/themes/ui.cjs) so a",
        "   kit is an override rather than a fork. */",
        "body, #workspace {",
        "  font-family: var(--font-sans);",
        "}",
        ".detail-title { font-family: var(--font-serif); }",
        ".research-row h4, .nav strong { font-family: var(--font-sans); }",
        ".card-eyebrow, .section-name, .table-head, .rail-title, .footer-note {",
        "  letter-spacing: 0.06em;",
        "}",
        ".project-card, .paper-card {",
        "  border-radius: 4px;",   # the kit is square; the template is 10px
        "}",
        ".brand-mark {",
        "  border-radius: 3px;",
        "}",
    ]

    return {
        "tokens.css": "\n".join(tokens) + "\n",
        "overlay.css": "\n".join(overlay) + "\n",
        "palette.json": json.dumps(
            {kit["id"]: pal}, ensure_ascii=False, indent=2) + "\n",
        "brand.json": json.dumps({
            "kit": kit["id"], "version": kit["version"], "name": kit["name"],
            "strings": bs, "fonts": fonts, "type_scale": type_scale,
        }, ensure_ascii=False, indent=2) + "\n",
        "INSTALL.md": (
            f"# {kit['name']} v{kit['version']}\n\n"
            f"{kit['description']}\n\n"
            "## Install\n\n"
            "```\npython platform/brand_kit.py install "
            f"{kit['id']}\n```\n\n"
            "Writes `brand-out/" + kit["id"] + "/`. Nothing under `upstream/` is read "
            "for writing or modified.\n\n"
            "## Use\n\n"
            "Point the Remotion render at the overlay:\n\n"
            "```\nremotion render src/index.ts out.mp4 "
            "--public-dir brand-out/" + kit["id"] + "\n```\n\n"
            "and import `tokens.css` before the template's stylesheet, "
            "`overlay.css` after it.\n\n"
            "## Uninstall\n\n"
            "```\npython platform/brand_kit.py uninstall " + kit["id"] + "\n```\n\n"
            "## What this deliberately does not set\n\n"
            f"{kit.get('motion', {}).get('note', '')}\n"
        ),
    }


def install(kid: str) -> int:
    kit = json.loads(kit_path(kid).read_text(encoding="utf-8"))
    before = upstream_fingerprint()
    dest = OUT / kid
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    for name, text in render(kit).items():
        (dest / name).write_text(text, encoding="utf-8")
    (dest / "kit.source.json").write_text(
        kit_path(kid).read_text(encoding="utf-8"), encoding="utf-8")

    after = upstream_fingerprint()
    changed = sorted(k for k in set(before) | set(after)
                     if before.get(k) != after.get(k))
    print(f"installed {kit['name']} -> brand-out/{kid}/")
    for p in sorted(dest.iterdir()):
        print(f"   {p.name}")
    if changed:
        print(f"\nFAIL: install modified {len(changed)} file(s) under upstream/: "
              f"{changed[:5]}", file=sys.stderr)
        return 1
    print(f"\nupstream untouched ({len(after)} files hashed before and after)")
    return 0


def verify(kid: str) -> int:
    dest = OUT / kid
    if not dest.is_dir():
        print(f"{kid} is not installed (no brand-out/{kid}/)", file=sys.stderr)
        return 1
    problems = []
    for name in ("tokens.css", "overlay.css", "palette.json", "brand.json"):
        if not (dest / name).exists():
            problems.append(f"{name} missing")
    kit = json.loads(kit_path(kid).read_text(encoding="utf-8"))
    tokens = (dest / "tokens.css").read_text(encoding="utf-8") if (dest / "tokens.css").exists() else ""
    for key, value in kit["palette"].items():
        if f"--{key.replace('_', '-')}: {value};" not in tokens:
            problems.append(f"palette {key} not emitted as a token")
    for key, value in kit["fonts"].items():
        if value not in tokens:
            problems.append(f"font {key} not emitted")
    pal = json.loads((dest / "palette.json").read_text(encoding="utf-8")) \
        if (dest / "palette.json").exists() else {}
    if pal.get(kid) != kit["palette"]:
        problems.append("palette.json does not match the kit")
    print(f"{kid}: {len(problems)} problem(s)")
    for p in problems:
        print("  -", p)
    return 1 if problems else 0


def uninstall(kid: str) -> int:
    dest = OUT / kid
    if not dest.exists():
        print(f"{kid} is not installed")
        return 0
    before = upstream_fingerprint()
    shutil.rmtree(dest)
    after = upstream_fingerprint()
    changed = sorted(k for k in set(before) | set(after)
                     if before.get(k) != after.get(k))
    print(f"removed brand-out/{kid}/")
    if changed:
        print(f"FAIL: uninstall modified upstream/: {changed[:5]}", file=sys.stderr)
        return 1
    print(f"upstream untouched ({len(after)} files)")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("action", choices=["list", "install", "verify", "uninstall"])
    ap.add_argument("kit", nargs="?", default="shotcraft")
    a = ap.parse_args()

    if a.action == "list":
        kits = list_kits()
        installed = sorted(p.name for p in OUT.iterdir()) if OUT.is_dir() else []
        print(f"kits in brand-kits/: {', '.join(kits) or 'none'}")
        print(f"installed in brand-out/: {', '.join(installed) or 'none'}")
        if UPSTREAM.is_dir():
            print(f"template brand surface (read-only): "
                  f"{', '.join(TEMPLATE_BRAND_SURFACE)}")
        return 0
    return {"install": install, "verify": verify,
            "uninstall": uninstall}[a.action](a.kit)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main())